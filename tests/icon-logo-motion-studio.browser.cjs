'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');

(async () => {
  const source = fs.readFileSync('site/icon-logo-motion-studio.js', 'utf8');
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.setContent('<div class="ui-layout-switcher"><button class="ui-layout-btn">Professional</button><button class="ui-layout-btn">Classic</button></div>');
    await page.addScriptTag({ content: source });
    await page.waitForSelector('#tm4ModeBtn');
    await page.click('#tm4ModeBtn');
    await page.waitForSelector('#tm4Overlay.open');
    assert.equal(await page.locator('#tm4Catalog .tm4-item').count(), 1500, 'catalog contains at least 1500 distinct logo concepts');
    const catalogNames = await page.locator('#tm4Catalog .tm4-item span').allTextContents();
    assert.equal(new Set(catalogNames).size, 1500, 'all 1500 logo names are unique and non-repeating');
    assert.match(await page.locator('#tm4MotifCount').innerText(), /1500 konsep logo vektor unik/);
    await page.locator('#tm4Search').fill('Aether Arc 0001');
    assert.equal(await page.locator('#tm4Catalog .tm4-item').count(), 1, 'exact logo search returns one distinct logo');
    await page.locator('#tm4Catalog .tm4-item').first().click();
    assert.equal(await page.locator('#tm4Layers .tm4-layer').count(), 6, 'adding an icon creates a layer in the five-logo composition');
    await page.locator('[data-out="svg"]').click();
    const svgOutput = await page.locator('#tm4Output').inputValue();
    assert.match(svgOutput, /<svg/);
    assert.doesNotMatch(svgOutput, /<rect[^>]+x=[\"']0[\"'][^>]+y=[\"']0[\"'][^>]+width=[\"']240[\"'][^>]+height=[\"']240[\"']/, 'logo artwork must not have a full-canvas rectangular frame');
    assert.match(svgOutput, /<circle\b/, 'illustrated icon includes recognizable internal details');
    assert.match(svgOutput, /stroke=\"#233449\"/, 'illustration uses the renderer dark outline palette');
    assert.match(svgOutput, /stroke-width=\"(?:4|5|6)\"/, 'illustration uses a bold outline weight');
    assert.match(svgOutput, /<(?:path|rect|circle|ellipse|polygon|line)\b/, 'logo is composed of real SVG vector geometry, not an emoji');
    assert.match(svgOutput, /class="tm4-part"/, 'SVG paths are split into independent animated parts');
    assert.match(svgOutput, /@keyframes [\w-]+(?:float|bob|pulse)/, 'per-part animation keyframes are embedded');
    assert.equal(await page.locator('#tm4PartMotion').count(), 1, 'per-part motion control is available');
    await page.locator('#tm4PartMotion').selectOption('Wave Parts');
    assert.equal(await page.locator('#tm4LayerMotion').count(), 1, 'per-layer motion selector is available');
    assert.equal(await page.locator('#tm4LayerStyle').count(), 1, 'per-layer visual style selector is available');
    assert.equal(await page.locator('#tm4Opacity').count(), 1, 'per-layer opacity control is available');
    assert.equal(await page.locator('#tm4SaveProject').count(), 1, 'project save control is available');
    assert.equal(await page.locator('#tm4LoadProject').count(), 1, 'project load control is available');
    for (const id of ['tm4AddEight','tm4RandomSet','tm4ArrangeGrid','tm4CenterSet','tm4MirrorSet','tm4RandomStyle']) assert.equal(await page.locator('#'+id).count(),1,'composition tool '+id+' is available');
    assert.equal(await page.locator('#tm4SceneTabs [data-scene]').count(),0,'storyboard scene tabs are removed');
    assert.match(await page.locator('#tm4SceneTabs').innerText(),/Acak Komposisi/,'composition tools replace storyboard controls');
    const projectDownload = page.waitForEvent('download');
    await page.locator('#tm4SaveProject').click();
    assert.match((await projectDownload).suggestedFilename(), /trozal-icon-motion-project\.json/);
    await page.locator('#tm4AddText').click();
    assert.equal(await page.locator('#tm4Layers .tm4-layer').count(), 7, 'text layer can be added');
    await page.locator('[data-out="svg"]').click();
    assert.match(await page.locator('#tm4Output').inputValue(), /<svg/);
    await page.locator('[data-out="html"]').click();
    assert.match(await page.locator('#tm4Output').inputValue(), /@keyframes move/);
    await page.locator('[data-out="video"]').click();
    assert.match(await page.locator('#tm4Output').inputValue(), /<section class="scene"/);
    assert.match(await page.locator('#tm4Output').inputValue(), /data-start=/, 'exported scenes preserve their own timeline offsets');
    assert.match(await page.locator('#tm4Output').inputValue(), /requestAnimationFrame\(frame\)/, 'exported HTML has a real multi-scene playback scheduler');
    const exportedHtml = await page.locator('#tm4Output').inputValue();
    const exportPage = await browser.newPage({ viewport: { width: 1280, height: 720 } });
    const exportErrors = [];
    exportPage.on('pageerror', error => exportErrors.push(error.message));
    await exportPage.setContent(exportedHtml, { waitUntil: 'domcontentloaded' });
    assert.equal(await exportPage.locator('.scene').count(), 1, 'exported HTML opens with one logo composition');
    await exportPage.waitForFunction(() => [...document.querySelectorAll('.scene')].some(scene => scene.style.opacity === '1'), null, { timeout: 3000 });
    assert.deepEqual(exportErrors, [], 'exported multi-scene HTML must run without browser exceptions');
    const stableSvg = await page.locator('#tm4Stage svg').first().evaluateHandle(el => el);
    await page.locator('#tm4Play').click();
    assert.match(await page.locator('#tm4Play').innerText(), /Pause/);
    await page.waitForTimeout(350);
    assert.equal(await stableSvg.evaluate(el => el === document.querySelector('#tm4Stage svg')), true, 'playback must not rebuild SVG DOM every animation frame');
    await page.locator('#tm4Play').click();
    assert.match(await page.locator('#tm4Play').innerText(), /Play/);
    console.log('Icon & Logo Motion Studio browser interaction test passed.');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exit(1); });
